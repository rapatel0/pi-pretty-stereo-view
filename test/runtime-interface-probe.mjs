import assert from "node:assert/strict";
import { agentEnv } from "./harness.mjs";
const { module: loadModule } = agentEnv({}, "ppsv-interface-");
const runtime = await loadModule("extensions/integrated/ui-runtime.ts");
const assistantOwner = {};
let revealed = false;
const projection = {
  revision: {}, activity: { render: () => ["Reasoning summary"], invalidate() {} },
  thinking: "Reasoning summary", text: "Answer", reveal: () => { revealed = true; },
};
runtime.setAssistantPaneProjector(assistantOwner, () => projection);
assert.equal(runtime.getAssistantPaneProjection(assistantOwner), projection);
runtime.getAssistantPaneProjection(assistantOwner).reveal();
assert.equal(revealed, true);
runtime.setAssistantPaneProjector(assistantOwner);
assert.equal(runtime.getAssistantPaneProjection(assistantOwner), undefined);
const order = [];
const offAttach = runtime.onStereoAttached(() => order.push("attach"));
const offDetach = runtime.onStereoDetaching(() => order.push("detach"));
runtime.markStereoAttached();
assert.equal(runtime.isStereoAttached(), true);
runtime.markStereoDetaching();
assert.equal(runtime.isStereoAttached(), false);
assert.deepEqual(order, ["attach", "detach"]);
offAttach(); offDetach();
runtime.markStereoAttached();
assert.equal(order.length, 2);
runtime.markStereoDetaching();
const foreign = {};
runtime.markForeignLayoutRoot(foreign);
assert.equal(runtime.isForeignLayoutRoot(foreign), true);
assert.equal(runtime.isForeignLayoutRoot({}), false);
for (const [set, get] of [["setPrettyTuiBridge", "getPrettyTuiBridge"], ["setStereoBridge", "getStereoBridge"], ["setPowerlineBridge", "getPowerlineBridge"]]) {
  const bridge = { enabled: () => true };
  runtime[set](bridge);
  assert.equal(runtime[get](), bridge);
}
const editor = {};
runtime.setEditorChromeActive(editor, true);
assert.equal(runtime.editorChromeActive(editor), true);
runtime.setEditorChromeActive(editor, false);
assert.equal(runtime.editorChromeActive(editor), false);
assert.ok(runtime.editorPrototype());
assert.ok(runtime.mouseInputPrototype());
const { getAgentDir } = await import("@earendil-works/pi-coding-agent");
assert.equal(runtime.getAgentDir(), getAgentDir());
const host = { layoutRoot: undefined, setLayoutRoot(value) { this.layoutRoot = value; } };
runtime.setLayoutRoot(host, foreign);
assert.equal(runtime.getLayoutRoot(host), foreign);
const ui = { setEditorComponent(value) { this.factory = value; } };
const factory = () => {};
runtime.setEditorFactory(ui, factory);
assert.equal(ui.factory, factory);
const history = runtime.getPromptHistoryState();
history.savedPromptHistory.push("draft");
assert.equal(runtime.getPromptHistoryState(), history);
const listener = () => {};
const second = () => {};
const tui = { inputListeners: new Set([listener]), addInputListener(fn) { this.inputListeners.add(fn); return () => this.inputListeners.delete(fn); }, hasOverlay: () => false };
const off = runtime.installPriorityInputListener(tui, second);
assert.deepEqual([...tui.inputListeners], [second, listener]);
off();
assert.equal(tui.inputListeners.size, 1);
assert.equal(runtime.isSidebarInputBlocked(tui), false);
let unsubscribed = false;
const unsubscribe = runtime.subscribeTerminalInput({ onTerminalInput(fn) { assert.equal(fn, listener); return () => { unsubscribed = true; }; } }, listener);
unsubscribe();
assert.equal(unsubscribed, true);
const native = new Map();
const pi = runtime.createUiRuntime({ on(name, fn) { const list = native.get(name) ?? []; list.push(fn); native.set(name, list); } });
const calls = [];
pi.on("message_end", async () => calls.push("first"));
pi.on("message_end", () => calls.push("second"));
assert.equal(native.get("message_end").length, 1);
await native.get("message_end")[0]({}, {});
assert.deepEqual(calls, ["first", "second"]);
pi.on("input", () => ({ action: "handled" }));
pi.on("input", () => ({ action: "continue" }));
assert.equal(native.get("input").length, 2);
assert.deepEqual(native.get("input")[0](), { action: "handled" });
pi.on("agent_end", () => { throw new Error("first error"); });
pi.on("agent_end", () => calls.push("after error"));
await assert.rejects(native.get("agent_end")[0](), /first error/);
assert.equal(calls.at(-1), "after error");
console.log("INTERFACE PASS: mount lifecycle, ownership, bridges, editor slot, history, input priority, listener order, and native return-value events");
